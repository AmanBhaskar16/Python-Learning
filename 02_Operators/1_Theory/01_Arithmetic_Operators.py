# ==================================
# ARITHMETIC OPERATORS
# ==================================

a = 10
b = 3

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Floor Division
print("Floor Division:", a // b)

# Modulus (Remainder)
print("Modulus:", a % b)

# Exponentiation
print("Power:", a ** b)


# Example: Even or Odd
num = 10

if num % 2 == 0:
    print("Even Number")
else:
    print("Odd Number")