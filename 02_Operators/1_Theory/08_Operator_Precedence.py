# ==================================
# OPERATOR PRECEDENCE
# ==================================

# Multiplication happens before addition
print(10 + 5 * 2)

# Parentheses have higher priority
print((10 + 5) * 2)

# Power
print(2 ** 3)

# Multiple operators
print(10 + 20 / 2 * 3)

# Comparison
print(10 + 5 > 12)

# Logical
print(True and False or True)


# Best Practice: Use parentheses
result = (10 + 5) * (20 - 10)

print(result)