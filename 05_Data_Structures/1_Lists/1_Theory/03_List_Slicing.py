# ==================================
# LIST SLICING
# ==================================

numbers = [10, 20, 30, 40, 50, 60]

# Basic Slicing
print(numbers[1:4])

# From Starting
print(numbers[:3])

# Till Ending
print(numbers[2:])

# Complete List
print(numbers[:])

# Step Slicing
print(numbers[::2])

# Reverse List
print(numbers[::-1])

# Negative Slicing
print(numbers[-4:-1])