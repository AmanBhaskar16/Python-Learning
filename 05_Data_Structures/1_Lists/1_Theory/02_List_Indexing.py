# ==================================
# LIST INDEXING
# ==================================

numbers = [10, 20, 30, 40, 50]

# Positive Indexing
print(numbers[0])
print(numbers[1])
print(numbers[2])

# Negative Indexing
print(numbers[-1])
print(numbers[-2])
print(numbers[-3])

# First Element
print(numbers[0])

# Last Element
print(numbers[-1])

# Update Element
numbers[2] = 100

print(numbers)

