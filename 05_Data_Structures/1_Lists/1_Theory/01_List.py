# List stores multiple values.

fruits = ["Apple", "Mango", "Banana"]

print(fruits)

# Access elements
print(fruits[0])
print(fruits[1])

# Modify elements
fruits[0] = "Orange"

print(fruits)

# Add elements
fruits.append("Grapes")

print(fruits)

# Remove elements
fruits.remove("Mango")

print(fruits)

# List can store different data types

data = [10, 20.5, "Python", True]

print(data)

# Duplicate values are allowed

numbers = [10, 20, 10, 30]

print(numbers)

# List length
print(len(fruits))