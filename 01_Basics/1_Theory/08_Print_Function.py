# =================================
# PYTHON PRINT FUNCTION
# =================================

# Basic Print

print("Hello Python")


# Multiple Values

print("Hello", "World", 100)


# Separator

print("Python", "Java", "C++", sep=" | ")


# End Parameter

print("Hello", end=" ")
print("World")


# Escape Characters

print("Hello\nWorld")

print("Hello\tPython")


# Formatted String

name = "Rahul"
age = 20

print(f"My name is {name} and my age is {age}")


# Mathematical Output

a = 10
b = 20

print("Sum =", a + b)