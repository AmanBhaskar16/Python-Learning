# =================================
# PYTHON DATA TYPES
# =================================

# 1. Integer

age = 20
print(age)
print(type(age))


# 2. Float

price = 99.99
print(price)
print(type(price))


# 3. String

name = "Python"
print(name)
print(type(name))


# 4. Boolean

is_active = True
print(is_active)
print(type(is_active))


# 5. List

fruits = ["Apple", "Mango", "Banana"]
print(fruits)
print(type(fruits))


# 6. Tuple

numbers = (10, 20, 30)
print(numbers)
print(type(numbers))


# 7. Set

unique_numbers = {1, 2, 3}
print(unique_numbers)
print(type(unique_numbers))


# 8. Dictionary

student = {
    "name": "Rahul",
    "age": 20
}

print(student)
print(type(student))


# 9. None

value = None
print(value)
print(type(value))