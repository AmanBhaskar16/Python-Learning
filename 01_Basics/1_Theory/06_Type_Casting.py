# PYTHON TYPE CASTING
# =================================

# Type casting converts one data type into another.

# Integer to Float

a = 10
b = float(a)

print(b)
print(type(b))


# Float to Integer

x = 10.99
y = int(x)

print(y)
print(type(y))


# Integer to String

num = 100
text = str(num)

print(text)
print(type(text))


# String to Integer

number = "500"
result = int(number)

print(result + 100)


# String to Float

price = "99.50"
new_price = float(price)

print(new_price)


# Integer to Boolean

print(bool(1))
print(bool(0))