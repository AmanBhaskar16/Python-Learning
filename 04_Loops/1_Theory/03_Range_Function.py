# ==================================
# RANGE FUNCTION
# ==================================

# range(stop)

for i in range(5):
    print(i)


# range(start, stop)

for i in range(1, 6):
    print(i)


# range(start, stop, step)

for i in range(1, 11, 2):
    print(i)


# Reverse range

for i in range(10, 0, -1):
    print(i)


# Even numbers

for i in range(2, 21, 2):
    print(i)