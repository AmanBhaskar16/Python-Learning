# ==================================
# PYTHON FOR LOOP
# ==================================

# Print numbers from 1 to 5

for i in range(1, 6):
    print(i)


# Loop through a string

name = "Python"

for char in name:
    print(char)


# Loop through a list

fruits = ["Apple", "Mango", "Banana"]

for fruit in fruits:
    print(fruit)


# Loop through a tuple

numbers = (10, 20, 30)

for num in numbers:
    print(num)